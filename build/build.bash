#!/bin/bash

# See the LICENSE file at the top of the project tree for
# copyright and license details.
#
# This script automates the process of preparing Firefox ESR
# for its use with I2Pd. It discovers the newest Firefox ESR
# branch, downloads it, verifies its integrity, extracts it,
# removes unnecessary files, updates configuration settings and
# extensions, and finally copies necessary scripts and
# configurations for the I2Pd Browser.

set -Eeuo pipefail

I2PD_BROWSER_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
# shellcheck disable=SC1091
source "$I2PD_BROWSER_ROOT/lib/i18n.bash"
i18n_init

trap 'error "Unhandled error at line $LINENO."' ERR

# Helper functions
if [[ -t 1 && ${NO_COLOR:-0} != "1" ]]; then
	GREEN="\033[32m"
	YELLOW="\033[33m"
	RED="\033[31m"
	RESET="\033[0m"
else
	GREEN=""
	YELLOW=""
	RED=""
	RESET=""
fi

log() {
	printf '%s %b[INFO]%b %s\n' \
		"$(date '+%Y-%m-%d %H:%M:%S')" \
		"$GREEN" "$RESET" "$*"
}

parse_args() {
	while (($#)); do
		case "$1" in
		--language=*) language="${1#*=}" ;;
		--language)
			[[ $# -ge 2 ]] || die "$(i18n_message error.argument-value --language)"
			language="$2"
			shift
			;;
		-h | --help)
			i18n_message usage.build-header "./build.bash"
			i18n_message usage.build-options
			exit 0
			;;
		*) die "$(i18n_message error.unknown-argument "$1")" ;;
		esac
		shift
	done
	language="$(i18n_normalize_locale "$language")" ||
		die "$(i18n_message language.invalid "$language")"
	i18n_init "$language"
}
warn() {
	printf '%s %b[WARN]%b %s\n' \
		"$(date '+%Y-%m-%d %H:%M:%S')" \
		"$YELLOW" "$RESET" "$*"
}

write_locale_preference() {
	local user_js="$staging_dir/data/user.js"
	printf '// Generated by I2Pd Browser; do not edit.\n' >"$user_js"
	printf 'user_pref("intl.locale.requested", "%s");\n' "$language" >>"$user_js"
	printf '%s\n' "$language" >"$staging_dir/.i2pd-browser-locale"
}
error() {
	printf '%s %b[ERROR]%b %s\n' \
		"$(date '+%Y-%m-%d %H:%M:%S')" \
		"$RED" "$RESET" "$*" >&2
}

die() {
	error "$*"
	exit 1
}
need() {
	command -v "$1" >/dev/null 2>&1 ||
		die "'$1' is required but not installed."
}

readonly -a REQUIRED_TOOLS=(
	curl
	sha512sum
	grep
	sed
	tar
	awk
	jq
	head
)

dir=""
arch=""
language="$I2PD_BROWSER_LANGUAGE"
# The newest ESR branch is published as the "next" ESR until it becomes
# the default. Use "firefox-esr-latest" to stay on the older branch.
ESR_PRODUCT="${ESR_PRODUCT:-firefox-esr-next-latest}"
# The product name is interpolated into a Mozilla URL. Keep it to the
# characters used by Mozilla's product identifiers.
if [[ ! $ESR_PRODUCT =~ ^[A-Za-z0-9._-]+$ ]]; then
	die "$(i18n_message error.invalid-product "$ESR_PRODUCT")"
fi
# Build into a staging directory and publish only after every step
# succeeds, so a failed build never removes a working browser.
staging_dir="../.browser-build"
fx_os=""
fx_dir=""
final_url=""
file=""
version=""
ftpmirror=""
filepath=""

setup_workdir() {
	dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" \
		&>/dev/null && pwd -P)"
	cd "$dir" ||
		die "Could not access the script directory: $dir"
}

check_tools() {
	local tool
	for tool in "${REQUIRED_TOOLS[@]}"; do
		need "$tool"
	done
}

detect_arch() {
	arch="$(uname -m)"

	case "$arch" in
	amd64 | x86_64)
		arch=x86_64
		fx_os="linux64"
		fx_dir="linux-x86_64"
		;;
	arm64 | aarch64)
		arch=aarch64
		fx_os="linux64-aarch64"
		fx_dir="linux-aarch64"
		;;
	i386 | i686)
		arch=i686
		fx_os="linux"
		fx_dir="linux-i686"
		;;
	*)
		die "Your system architecture is not supported: $arch"
		;;
	esac
}

resolve_latest_firefox() {
	log "$(i18n_message info.build.resolve "$fx_os ($arch)" "$language")"
	# -f makes curl fail on HTTP errors so an unavailable platform
	# (for example 32-bit Linux, which Mozilla no longer publishes in
	# the current ESR branch) is reported here instead of producing a
	# confusing "could not parse the version" error later.
	final_url="$(curl -fs -L -I -o /dev/null \
		-w '%{url_effective}' \
		"https://download.mozilla.org/\
?product=${ESR_PRODUCT}&os=${fx_os}&lang=${language}")" ||
		die "Failed to resolve a ${ESR_PRODUCT} build for" \
			"$fx_os ($arch); the platform may no longer be" \
			"published (try ESR_PRODUCT=firefox-esr-latest)."

	[[ -n $final_url ]] ||
		die "Could not resolve the Firefox download" \
			"URL via the redirector."

	# A redirect to a fallback locale would pass a checksum check but
	# leave the bundle in the wrong language. Reject it explicitly.
	if [[ $final_url != *"/$language/"* ]]; then
		die "$(i18n_message error.invalid-locale-build "$language")"
	fi

	file="$(basename "$final_url")"

	if [[ $file =~ ^firefox-([0-9.]+esr)\.tar\.(xz|bz2)$ ]]; then
		version="${BASH_REMATCH[1]}"
	else
		die "Could not parse the version from filename: $file"
	fi

	ftpmirror="https://ftp.mozilla.org/pub/firefox/releases/$version"
	filepath="$fx_dir/$language/$file"

	log "$(i18n_message info.build.preparing "$version")"
}

download_firefox() {
	log "$(i18n_message info.build.downloading "$version")"
	curl -L -f -# -O "$final_url" ||
		die "Could not download the file." \
			"Check your internet connection."
	[[ -f $file ]] ||
		die "Downloaded file not found: $file"
}

verify_checksum() {
	local recv_sum
	local file_sum

	log "$(i18n_message info.build.checksum)"
	curl -L -f -# -O "$ftpmirror/SHA512SUMS" ||
		die "Could not download SHA512SUMS."

	recv_sum="$(awk -v f="$filepath" \
		'$NF==f {print $1; exit}' SHA512SUMS)"
	file_sum="$(sha512sum "$file" | awk '{print $1}')"

	if [[ -z $recv_sum || $recv_sum != "$file_sum" ]]; then
		die "$(i18n_message error.checksum)"
	fi

	log "$(i18n_message info.build.checksum-ok)"
	rm -f SHA512SUMS
}

extract_archive() {
	log "$(i18n_message info.build.extracting)"
	[[ -e firefox ]] && rm -rf firefox
	rm -rf "$staging_dir"
	case "$file" in
	*.tar.xz) tar xJf "$file" ;;
	*.tar.bz2) tar xjf "$file" ;;
	*) tar xf "$file" ;;
	esac
	rm -f "$file"
	mv firefox "$staging_dir"
	mkdir -p "$staging_dir/data"

	# Keep the portable profile across rebuilds. Without this, a
	# language change or a rebuild would delete bookmarks, history,
	# cookies, logins and extensions stored in browser/data.
	if [[ -d ../browser/data ]]; then
		cp -a ../browser/data/. "$staging_dir/data/"
		# Stale profile locks must not make the new bundle look as if
		# it is already in use.
		rm -f "$staging_dir/data/.parentlock" \
			"$staging_dir/data/parent.lock" \
			"$staging_dir/data/lock"
	fi
}

remove_unneeded_files() {
	local -a files_to_remove=(
		"$staging_dir"/crashreporter*
		"$staging_dir"/crashhelper
		"$staging_dir"/minidump-analyzer
		"$staging_dir"/pingsender
		"$staging_dir"/precomplete
		"$staging_dir"/removed-files
		"$staging_dir"/update*
		"$staging_dir"/maintenanceservice*
		"$staging_dir"/default-browser-agent*
		"$staging_dir"/Throbber-small.gif
		"$staging_dir"/browser/crashreporter-override.ini
		"$staging_dir"/browser/features/formautofill@mozilla.org.xpi
		"$staging_dir"/browser/features/screenshots@mozilla.org.xpi
		"$staging_dir"/browser/features/webcompat-reporter@mozilla.org.xpi
	)

	log "$(i18n_message info.build.removing)"
	# update* matches both files and directories, so use recursive
	# removal for the whole fixed list.
	rm -rf "${files_to_remove[@]}"
	rm -rf "$staging_dir/icons"
}

update_configs() {
	log "$(i18n_message info.build.configuring)"
	[[ -f $staging_dir/application.ini ]] ||
		die "Firefox application.ini is missing."
	sed -i 's/Enabled=1/Enabled=0/g' "$staging_dir/application.ini"
	sed -i 's/ServerURL=.*/ServerURL=-/' "$staging_dir/application.ini"
}

download_noscript() {
	local xpi="$staging_dir/browser/extensions"
	xpi+="/{73a6fe31-595d-460b-a920-fcc0f8843232}.xpi"

	log "$(i18n_message info.build.noscript)"
	mkdir -p "$staging_dir/browser/extensions"
	curl -L -f -# -o "$xpi" \
		"https://addons.mozilla.org/firefox/\
downloads/latest/noscript/latest.xpi"

	# AMO can return an HTML error page with a successful HTTP status.
	# An XPI is a ZIP file, so require the ZIP magic before publishing.
	if [[ ! -s $xpi ]] || [[ $(head -c 2 "$xpi") != "PK" ]]; then
		die "NoScript download is not a valid XPI."
	fi
}

copy_standard_configs() {
	log "$(i18n_message info.build.standard-config)"
	cp -r preferences/* "$staging_dir/"
	cp -r profile/* "$staging_dir/data/"
}

format_distribution_policy_json() {
	local json_file="$staging_dir/distribution/policies.json"
	local tmp_json_file="${json_file}.tmp"

	log "$(i18n_message info.build.configuring)"
	jq . "$json_file" >"$tmp_json_file"
	cat "$tmp_json_file" >"$json_file"
	rm -f "$tmp_json_file"
}

validate_bundle() {
	local required
	local -a required_files=(
		application.ini
		i2pd-browser.cfg
		defaults/pref/autoconfig.js
		distribution/policies.json
		browser/override.ini
		data/user.js
		.i2pd-browser-locale
		start-i2pd-browser.bash
		start-i2pd-browser.ps1
		i18n.bash
		i18n.ps1
		locales/en-US.properties
	)
	local -a missing=()

	for required in "${required_files[@]}"; do
		[[ -e $staging_dir/$required ]] || missing+=("$required")
	done
	if ((${#missing[@]})); then
		die "$(i18n_message error.bundle-validation "${missing[*]}")"
	fi

	# The proxy endpoint lives only in policies.json. Refuse to publish
	# a bundle that could run Firefox in manual proxy mode without it.
	jq -e '
		.policies.Proxy.Mode == "manual" and
		.policies.Proxy.Locked == true and
		.policies.Proxy.HTTPProxy == "127.0.0.1:4444" and
		.policies.Proxy.SSLProxy == "127.0.0.1:4444" and
		.policies.Proxy.UseProxyForDNS == true and
		.policies.Proxy.Passthrough == ""
	' "$staging_dir/distribution/policies.json" >/dev/null ||
		die "$(i18n_message error.bundle-validation "Proxy policy")"
}

copy_launch_scripts() {
	log "$(i18n_message info.build.launchers)"
	cp -r scripts/* "$staging_dir/"
	# Both launchers are shipped in the bundle so a copy remains
	# usable when moved between platforms.
	cp ../lib/i18n.bash "$staging_dir/"
	cp ../lib/i18n.ps1 "$staging_dir/"
	cp -r ../locales "$staging_dir/"
	cp scripts/start-i2pd-browser.desktop ../
}

publish_browser() {
	local final="../browser"
	local backup="../.browser-old"

	if [[ -e $final ]]; then
		rm -rf "$backup"
		mv "$final" "$backup" || die "Could not move the old browser aside."
	fi
	if ! mv "$staging_dir" "$final"; then
		[[ -d $backup ]] && mv "$backup" "$final"
		die "Could not publish the new browser."
	fi
	rm -rf "$backup"
}

main() {
	parse_args "$@"
	setup_workdir
	check_tools
	detect_arch
	resolve_latest_firefox
	download_firefox
	verify_checksum
	extract_archive
	remove_unneeded_files
	update_configs
	download_noscript
	copy_standard_configs
	format_distribution_policy_json
	copy_launch_scripts
	write_locale_preference
	validate_bundle
	publish_browser
	log "$(i18n_message info.build.complete)"
}

main "$@"
